/**
 * Snapshot the transforms' per-element-type style key tables into this repo.
 *
 * Two schema pages state which style keys an element type may carry — the
 * anatomy page's `Styles` section and the style page's `Elements Supported`
 * section — and the tables that decide it are declared in `specs-transforms`,
 * a private sibling checkout. The deploy builds this repo alone, with no
 * sibling beside it, so a generator reaching sideways finds nothing. Until
 * 2026-11-20 both generators did exactly that and dropped their section in
 * silence: every local build showed it, every production build omitted it, and
 * nothing failed.
 *
 * So the data crosses the repo boundary here, once, as a committed artifact:
 *
 *   sibling present (your machine)  → refresh the snapshot from it
 *   sibling absent (CI, a fresh clone) → leave the committed snapshot alone
 *
 * Both generators read only the snapshot, so local and production render from
 * the same bytes. The snapshot is tracked, not generated at deploy time — that
 * is what makes it visible in review and present in the deploy.
 *
 * Usage:
 *   node scripts/build-element-style-keys.mjs           refresh (or keep) and report
 *   node scripts/build-element-style-keys.mjs --check    exit 1 if it is stale or absent
 *
 * `--check` is the release gate: it fails when the sibling's tables have moved
 * and the refreshed snapshot was never committed.
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { site, transforms } from './lib/paths.mjs';

/** The committed artifact both generators read. */
export const SNAPSHOT = join(site, 'data/element-style-keys.json');

/**
 * The two declared tables, by the direction each governs. Keys are the
 * transforms' own element vocabulary (`frame`, `component`), not the schema's —
 * the mapping to schema types stays in the generators that consume this, where
 * it was already written.
 */
const SOURCES = {
  capture: join(transforms, 'packages/specs-from-figma/src/Component/Styles/style-bindings.json'),
  render: join(transforms, 'packages/figma-from-specs/src/Styles/style-bindings.json'),
};

const readSources = () => {
  const out = {};
  for (const [direction, path] of Object.entries(SOURCES)) {
    if (!existsSync(path)) return null;
    out[direction] = JSON.parse(readFileSync(path, 'utf8')).elements;
  }
  return out;
};

const serialize = (elements) =>
  `${JSON.stringify(
    {
      $comment:
        'Generated by site/scripts/build-element-style-keys.mjs from the specs-transforms style-bindings tables. Committed so the deploy, which checks out this repo alone, renders the same sections a local build does. Refresh by running that script with specs-transforms checked out beside this repo; never hand-edit.',
      elements,
    },
    null,
    2,
  )}\n`;

/** The snapshot's tables, for a generator. Throws when it is missing. */
export function elementStyleKeys() {
  if (!existsSync(SNAPSHOT)) {
    throw new Error(
      `element style keys: ${SNAPSHOT} is missing.\n` +
        'Run `node scripts/build-element-style-keys.mjs` with specs-transforms checked out\n' +
        'beside this repo, and commit the result. The pages that state which style keys an\n' +
        'element type carries cannot be built without it, and publishing them with the\n' +
        'section silently absent is the failure this file exists to prevent.',
    );
  }
  return JSON.parse(readFileSync(SNAPSHOT, 'utf8')).elements;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const check = process.argv.includes('--check');
  const fresh = readSources();
  const current = existsSync(SNAPSHOT) ? readFileSync(SNAPSHOT, 'utf8') : null;

  if (!fresh) {
    if (!current) {
      console.error(
        'element style keys: no snapshot, and specs-transforms is not checked out beside this repo.',
      );
      process.exit(1);
    }
    console.log('element style keys: sibling absent — keeping the committed snapshot');
    process.exit(0);
  }

  const next = serialize(fresh);
  if (current === next) {
    console.log('element style keys: snapshot current');
    process.exit(0);
  }

  if (check) {
    console.error(
      'element style keys: the snapshot is stale against specs-transforms.\n' +
        'Run `node scripts/build-element-style-keys.mjs` and commit the result —\n' +
        'otherwise the deploy renders these sections from the older tables.',
    );
    process.exit(1);
  }

  mkdirSync(dirname(SNAPSHOT), { recursive: true });
  writeFileSync(SNAPSHOT, next);
  console.log(`element style keys: ${current ? 'updated' : 'written'} ${SNAPSHOT}`);
}
